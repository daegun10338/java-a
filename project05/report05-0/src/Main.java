public class Main {
    public static void main(String[] args) {
        int i = 10;
        int j = 3;
        int age = 10;
        int b = 15;
        int c = 20;

        System.out.println(i % j == 0);
        System.out.println(age <= 12);
        System.out.println(age < b && age > c);
        System.out.println(age - 5 == 10);
        System.out.println(age != b || age == c);
        System.out.println(Character.isLowerCase('c'));
    }
}
